#!/bin/sh
# FreeRDP 3 (Ubuntu's 3.32.1 source, patches applied) with the gfxredir server channel, which Ubuntu does not build
# (channels/gfxredir/ChannelOptions.cmake: OPTION_DEFAULT OFF). Server side only, into a private prefix.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd); . "$HERE/env.sh"
S=$WORK/freerdp-src
B=$WORK/build-freerdp
P=$FREERDP_PREFIX
E="env -i HOME=$HOME PATH=/usr/bin:/bin LANG=C.UTF-8"
if [ ! -f "$B/build.ninja" ]; then
  $E cmake -S "$S" -B "$B" -G Ninja -DCMAKE_INSTALL_PREFIX="$P" -DCMAKE_INSTALL_LIBDIR=lib \
    -DCMAKE_BUILD_TYPE=RelWithDebInfo -DCMAKE_SKIP_INSTALL_RPATH=FALSE '-DCMAKE_INSTALL_RPATH=$ORIGIN' \
    -DWITH_CHANNELS=ON -DWITH_SERVER=ON -DCHANNEL_GFXREDIR=ON \
    -DWITH_CLIENT=OFF -DWITH_CLIENT_COMMON=OFF -DWITH_CLIENT_SDL=OFF -DWITH_SHADOW=OFF -DWITH_PROXY=OFF -DWITH_SAMPLE=OFF \
    -DBUILD_TESTING=OFF -DWITH_MANPAGES=OFF -DWITH_X11=OFF -DWITH_WAYLAND=OFF -DWITH_PULSE=OFF -DWITH_ALSA=OFF \
    -DWITH_CUPS=OFF -DWITH_PCSC=OFF -DWITH_ICU=OFF -DWITH_KERBEROS=OFF -DWITH_OPUS=OFF -DWITH_FFMPEG=OFF -DWITH_SWSCALE=OFF -DWITH_DSP_FFMPEG=OFF -DWITH_VIDEO_FFMPEG=OFF \
    -DWITH_VAAPI=OFF -DWITH_OPENH264=OFF -DWITH_WEBVIEW=OFF -DWITH_CLANG_FORMAT=OFF -DWITH_DEBUG_ALL=OFF \
    -DWITH_BINARY_VERSIONING=OFF -DWITH_JSONC_REQUIRED=ON -DWITH_WINPR_TOOLS=OFF -DWITH_INSTALL_CLIENT_DESKTOP_FILES=OFF
fi
$E ninja -C "$B"
$E ninja -C "$B" install
